import type { Article, Block } from './types'

const CON = 'DOS · console'
const SYS = 'DOS · system'

/** Print the character in DL. */
const PUTC = ['MOV     AH, 02h          ; DOS: print the character in DL', 'INT     21h']
/** Print the character c (a quoted character or a number). */
const putc = (c: string): string[] => ['MOV     DL, ' + c, ...PUTC]
/** Print the $-terminated string `name`. */
const SHOW = (name: string): string[] => ['MOV     DX, OFFSET ' + name, 'MOV     AH, 09h          ; DOS: print the string at DS:DX', 'INT     21h']
/** Put one keystroke into the BIOS keyboard buffer, as if it had been typed: CH = scan code, CL = ASCII. */
const press = (cx: string, what: string): string[] => [
  'MOV     CX, ' + cx + '        ; ' + what,
  'MOV     AH, 05h          ; BIOS: store a keystroke in the keyboard buffer',
  'INT     16h',
]

