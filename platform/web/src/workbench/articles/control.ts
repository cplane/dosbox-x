import type { Article, Block } from './types'

/** Pad a mnemonic to the guide's 8-column field. */
const pad = (m: string): string => (m + '        ').slice(0, 8)

/** Print the character in DL. */
const PUTC = ['MOV     AH, 02h          ; DOS: print the character in DL', 'INT     21h']

/** Print AL as a decimal digit (0-9). */
const DIGIT = ['ADD     AL, "0"          ; digit -> character', 'MOV     DL, AL', ...PUTC]

/** Print Y when the jump is taken, N when it is not. Goes right after the instruction that sets the flags. */
const yesNo = (jump: string): string[] => [
  'MOV     DL, "Y"          ; MOV leaves the flags alone',
  pad(jump) + 'SHOW1            ; taken: DL stays "Y"',
  'MOV     DL, "N"',
  'SHOW1:',
  ...PUTC,
]

