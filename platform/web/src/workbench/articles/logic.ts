/** Data-side helper for the examples: print AL as eight '0'/'1' characters and a space. Keeps every register and
 *  the flags, so a caller can still look at CF afterwards. */
const SHOWBIN = [
  'SHOWBIN PROC    NEAR             ; print AL as 8 binary digits and a space',
  'PUSHF                            ; keep the caller\'s flags',
  'PUSH    AX',
  'PUSH    BX',
  'PUSH    CX',
  'PUSH    DX',
  'MOV     BL, AL',
  'MOV     CX, 8',
  'NEXTBIT:',
  'SHL     BL, 1            ; the top bit falls into CF',
  'MOV     DL, "0"',
  'ADC     DL, 0            ; "0" + CF = "0" or "1"',
  'MOV     AH, 02h',
  'INT     21h',
  'LOOP    NEXTBIT',
  'MOV     DL, " "',
  'MOV     AH, 02h',
  'INT     21h',
  'POP     DX',
  'POP     CX',
  'POP     BX',
  'POP     AX',
  'POPF',
  'RET',
  'SHOWBIN ENDP',
]

