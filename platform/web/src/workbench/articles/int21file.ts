const CRLF = ['CRLF    DB      13, 10, "$"']
const BUF = ['BUF     DB      64 DUP (?)']

/** Print AL as two hex digits; keeps every register but AX. */
const PHEXB = [
  'PHEXB   PROC    NEAR     ; print AL as two hex digits',
  'PUSH    CX',
  'PUSH    DX',
  'MOV     DH, AL           ; keep the byte',
  'MOV     CL, 4',
  'SHR     AL, CL           ; the high digit first',
  'MOV     CX, 2',
  'PHEXB1:',
  'AND     AL, 0Fh',
  'ADD     AL, "0"',
  'CMP     AL, "9"',
  'JBE     PHEXB2',
  'ADD     AL, 7            ; 10..15 -> "A".."F"',
  'PHEXB2:',
  'MOV     DL, AL',
  'MOV     AH, 02h          ; DOS: print DL',
  'INT     21h',
  'MOV     AL, DH           ; then the low digit',
  'LOOP    PHEXB1',
  'POP     DX',
  'POP     CX',
  'RET',
  'PHEXB   ENDP',
]
/** Print AX as four hex digits (needs PHEXB). */
const PHEX = [
  'PHEX    PROC    NEAR     ; print AX as four hex digits',
  'PUSH    AX',
  'MOV     AL, AH',
  'CALL    PHEXB',
  'POP     AX',
  'CALL    PHEXB',
  'RET',
  'PHEX    ENDP',
]
