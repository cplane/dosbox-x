const G = 'DOS · files'

/** Print the $-terminated string `name`. */
const SHOW = (name: string) => ['MOV     DX, OFFSET ' + name, 'MOV     AH, 09h          ; DOS: print the string at DS:DX', 'INT     21h']
/** Print one character. */
const PUTC = (c: string) => [`MOV     DL, "${c}"`, 'MOV     AH, 02h          ; DOS: print DL', 'INT     21h']
/** Create TEST.TXT (the name at FNAME) and keep its handle in BX. */
const CREATE = [
  'MOV     AH, 3Ch          ; DOS: create TEST.TXT',
  'XOR     CX, CX           ; CX = 0: normal attributes',
  'MOV     DX, OFFSET FNAME',
  'INT     21h',
  'CALL    CHECK            ; stop if CF = 1',
  'MOV     BX, AX           ; BX = the handle',
]
/** Close the handle in BX and delete TEST.TXT. */
const CLEANUP = [
  'MOV     AH, 3Eh          ; close the handle',
  'INT     21h',
  'MOV     AH, 41h          ; delete TEST.TXT',
  'MOV     DX, OFFSET FNAME',
  'INT     21h',
]

