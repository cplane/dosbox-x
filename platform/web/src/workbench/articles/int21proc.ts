/** Print the $-terminated string `name`. */
const SHOW = (name: string) => ['MOV     DX, OFFSET ' + name, 'MOV     AH, 09h', 'INT     21h']

const CRLF = 'CRLF    DB      13, 10, "$"'

/** Print AX in decimal. */
const PDEC = [
  'PDEC    PROC    NEAR     ; print AX in decimal (changes AX BX CX DX)',
  'MOV     BX, 10',
  'XOR     CX, CX           ; digits on the stack',
  'PDEC1:',
  'XOR     DX, DX',
  'DIV     BX               ; AX = AX / 10, DX = the last digit',
  'PUSH    DX',
  'INC     CX',
  'OR      AX, AX',
  'JNZ     PDEC1',
  'PDEC2:',
  'POP     DX               ; the digits come back first to last',
  'ADD     DL, "0"',
  'MOV     AH, 02h',
  'INT     21h',
  'LOOP    PDEC2',
  'RET',
  'PDEC    ENDP',
]

/** Print DX:AX in decimal. */
const PDEC32 = [
  'PDEC32  PROC    NEAR     ; print DX:AX in decimal (changes AX BX CX DX DI)',
  'MOV     BX, 10',
  'XOR     CX, CX',
  'PDEC32A:',
  'PUSH    AX               ; DX:AX / 10 in two steps:',
  'MOV     AX, DX',
  'XOR     DX, DX',
  'DIV     BX               ; the high word first',
  'MOV     DI, AX           ; the high word of the quotient',
  'POP     AX',
  'DIV     BX               ; then remainder:low word',
  'PUSH    DX               ; a digit',
  'INC     CX',
  'MOV     DX, DI           ; DX:AX = the quotient',
  'OR      DI, AX',
  'JNZ     PDEC32A',
  'PDEC32B:',
  'POP     DX',
  'ADD     DL, "0"',
  'MOV     AH, 02h',
  'INT     21h',
  'LOOP    PDEC32B',
  'RET',
  'PDEC32  ENDP',
]

/** Print AX as four hex digits. */
const PHEX = [
  'PHEX    PROC    NEAR     ; print AX as four hex digits (changes AX BX CX DX)',
  'MOV     BX, AX',
  'MOV     CX, 4',
  'PHEX1:',
  'PUSH    CX',
  'MOV     CL, 4',
  'ROL     BX, CL           ; the top digit to the bottom',
  'POP     CX',
  'MOV     DL, BL',
  'AND     DL, 0Fh',
  'ADD     DL, "0"',
  'CMP     DL, "9"',
  'JBE     PHEX2',
  'ADD     DL, 7            ; "A" to "F"',
  'PHEX2:',
  'MOV     AH, 02h',
  'INT     21h',
  'LOOP    PHEX1',
  'RET',
  'PHEX    ENDP',
]

/** Print "ok" or "error n" from CF and AX; keeps AX and the flags. Needs PDEC and CRLF. */
const RESULT = [
  'RESULT  PROC    NEAR     ; print "ok", or "error" and AX when CF = 1',
  'PUSHF                    ; keeps AX and CF for the caller',
  'PUSH    AX',
  'MOV     DX, OFFSET OKMSG',
  'JNC     RESULT1',
  'MOV     DX, OFFSET ERRMSG',
  'MOV     AH, 09h',
  'INT     21h',
  'POP     AX',
  'PUSH    AX',
  'CALL    PDEC             ; the error code',
  'MOV     DX, OFFSET CRLF',
  'RESULT1:',
  'MOV     AH, 09h',
  'INT     21h',
  'POP     AX',
  'POPF',
  'RET',
  'RESULT  ENDP',
  'OKMSG   DB      "ok", 13, 10, "$"',
  'ERRMSG  DB      "error $"',
]

