/** One line in the guide's layout: the mnemonic (or a name and its directive) padded to 8 columns, the comment
 *  from column 25. Labels stay as they are. Written compactly here ('MOV AH, 09h ; why'), laid out on load. */
function fmt(line: string): string {
  let quoted = false
  let cut = -1
  for (let i = 0; i < line.length; i++) {
    if (line[i] === '"') quoted = !quoted
    else if (line[i] === ';' && !quoted) { cut = i; break }
  }
  const code = (cut < 0 ? line : line.slice(0, cut)).trim()
  const note = cut < 0 ? '' : line.slice(cut + 1).trim()
  const col = (s: string): string => (s.length < 8 ? (s + '        ').slice(0, 8) : s + ' ')
  let out = code
  const m = /^(\S+)\s+(.*)$/.exec(code)
  if (m) {
    const d = /^(DB|DW|DD|EQU)\s+(.*)$/i.exec(m[2])
    out = d ? col(m[1]) + col(d[1]) + d[2] : col(m[1]) + m[2]
  }
  if (!note) return out
  if (!out) return '; ' + note
  return (out.length < 25 ? (out + ' '.repeat(25)).slice(0, 25) : out + ' ') + '; ' + note
}

/** Lines (and groups of lines) in the guide's layout. */
const A = (...parts: (string | string[])[]): string[] => parts.flat().map(fmt)

/** DOS: print the $-terminated string at msg. */
const say = (msg: string, why = ''): string[] => ['MOV AH, 09h', `MOV DX, OFFSET ${msg}` + (why ? ' ; ' + why : ''), 'INT 21h']

